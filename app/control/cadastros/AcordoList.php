    /**
     * Register the filter in the session
     */
    public function onSearch($param = null)
    {
        $data = $this->form->getData();
        $filters = [];

        TSession::setValue(__CLASS__.'_filter_data', NULL);
        TSession::setValue(__CLASS__.'_filters', NULL);

        if (isset($data->nr_jet) AND ( (is_scalar($data->nr_jet) AND $data->nr_jet !== '') OR (is_array($data->nr_jet) AND (!empty($data->nr_jet)) )) )
        {

            $filters[] = new TFilter('nr_jet', '=', $data->nr_jet);// create the filter 
        }

        if (isset($data->nr_nota) AND ( (is_scalar($data->nr_nota) AND $data->nr_nota !== '') OR (is_array($data->nr_nota) AND (!empty($data->nr_nota)) )) )
        {

            $filters[] = new TFilter('nr_nota', 'like', "%{$data->nr_nota}%");// create the filter 
        }

        if (isset($data->valor) AND ( (is_scalar($data->valor) AND $data->valor !== '') OR (is_array($data->valor) AND (!empty($data->valor)) )) )
        {

            $filters[] = new TFilter('valor', '=', $data->valor);// create the filter 
        }

        if (isset($data->carteirinha) AND ( (is_scalar($data->carteirinha) AND $data->carteirinha !== '') OR (is_array($data->carteirinha) AND (!empty($data->carteirinha)) )) )
        {

            $filters[] = new TFilter('carteirinha', 'like', "%{$data->carteirinha}%");// create the filter 
        }

        if (isset($data->beneficiario) AND ( (is_scalar($data->beneficiario) AND $data->beneficiario !== '') OR (is_array($data->beneficiario) AND (!empty($data->beneficiario)) )) )
        {

            $filters[] = new TFilter('beneficiario', 'like', "%{$data->beneficiario}%");// create the filter 
        }

